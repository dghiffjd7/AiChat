import {
  buildLlmCharacterContext,
  buildLlmGroupContext,
  buildLlmSessionContext,
  buildLlmUserContext,
} from './llm-context-section-utils.js';
import {
  buildLlmContextMeta,
  buildLlmContextMetaInput,
  resolveLlmMemoryRuntimeConfig,
} from './llm-context-meta-utils.js';

export const buildLlmContextPayload = ({
  activePersona = null,
  activeUser = null,
  attachmentParts = [],
  buildHistory = null,
  characterName = '',
  continueTarget = null,
  disableSummary = false,
  getContactName = null,
  groupMembers = [],
  injectedPromptBlocks = [],
  isGroupChat = false,
  isRpMode = false,
  lastChatBridgeSessionId = '',
  memoryAutoExtract = false,
  memoryStorageMode = '',
  openaiPreset = null,
  pendingUserText = '',
  promptUserName = '',
  replyPromptHint = '',
  rpBridgeSessionId = '',
  rpUiMode = false,
  sessionId = '',
  sessionSettings = null,
  settings = null,
  sharedVariables = false,
  skipInputRegex = false,
  skipScripts = false,
  skipTemplate = false,
  stagePromptBlocks = [],
  uiMode = 'chat',
} = {}) => {
  const memoryRuntime = resolveLlmMemoryRuntimeConfig({ openaiPreset, settings });
  return {
    user: buildLlmUserContext({
      promptUserName,
      activeUser,
    }),
    character: buildLlmCharacterContext({
      characterName,
      activePersona,
    }),
    session: buildLlmSessionContext({
      sessionId,
      isGroupChat,
      characterName,
      sessionSettings: sessionSettings || {},
    }),
    meta: buildLlmContextMeta(buildLlmContextMetaInput({
      disableSummary,
      skipInputRegex,
      continueTarget,
      rpUiMode,
      uiMode,
      sharedVariables,
      isRpMode,
      rpBridgeSessionId,
      lastChatBridgeSessionId,
      memoryStorageMode,
      memoryAutoExtract,
      memoryRuntime,
      attachmentParts,
      replyPromptHint,
      stagePromptBlocks,
      injectedPromptBlocks,
      skipTemplate,
      skipScripts,
    })),
    group: buildLlmGroupContext({
      isGroupChat,
      sessionId,
      characterName,
      groupMembers,
      getContactName,
    }),
    history: typeof buildHistory === 'function' ? buildHistory(pendingUserText) : [],
  };
};
